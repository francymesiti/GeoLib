CREATE EXTENSION IF NOT EXISTS postgis;
CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, city TEXT NOT NULL DEFAULT '',
 location GEOGRAPHY(POINT,4326), created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS books (
 id SERIAL PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title TEXT NOT NULL, author TEXT NOT NULL, isbn TEXT DEFAULT '', category TEXT NOT NULL,
 description TEXT DEFAULT '', cover_url TEXT DEFAULT '', available BOOLEAN DEFAULT TRUE,
 location GEOGRAPHY(POINT,4326) NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS books_location_idx ON books USING GIST(location);
CREATE TABLE IF NOT EXISTS loans (
 id SERIAL PRIMARY KEY, book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 requester_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','returned')),
 created_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(book_id, requester_id)
);
CREATE TABLE IF NOT EXISTS book_views (
 id BIGSERIAL PRIMARY KEY, book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 viewed_at TIMESTAMPTZ DEFAULT NOW()
);
